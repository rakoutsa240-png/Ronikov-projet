// "Plus de super" or "longue file", as written into a report notification.
function reportLabel(label: string): string {
  const capitalised = label.charAt(0).toUpperCase() + label.slice(1);
  const exact = EN[capitalised];
  if (exact) return exact;
  const noFuel = capitalised.match(/^Plus de (.+)$/);
  if (noFuel) return `No more ${fuel(noFuel[1].charAt(0).toUpperCase() + noFuel[1].slice(1)).toLowerCase()}`;
  const wrongPrice = capitalised.match(/^Prix du (.+) faux$/);
  if (wrongPrice) return `Wrong ${fuel(wrongPrice[1].charAt(0).toUpperCase() + wrongPrice[1].slice(1)).toLowerCase()} price`;
  return label;
}
